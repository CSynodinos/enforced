#  Reporting: one structure, rendered to the terminal (ANSI) and Markdown
# ═════════════════════════════════════════════════════════════════════════════

ANSI = re.compile(r"\x1b\[[0-9;]*m")
STYLES = {"best": "1;32", "good": "32", "bad": "31", "warn": "33", "dim": "2", "head": "1", "title": "1;36", "lib": "1"}


@dataclasses.dataclass
class Cell:
    text: str
    style: str | None = None


def cell(x: Any, style: str | None = None) -> Cell:
    return x if isinstance(x, Cell) else Cell(str(x), style)


MD_SPECIAL = re.compile(r"([\\|*<`~])")


def md_escape(text: str) -> str:
    """Escape what Markdown would read as formatting or HTML (``|`` would also end a table cell)."""
    return MD_SPECIAL.sub(r"\\\1", text)


class Report:
    def __init__(self, color: bool) -> None:
        self.color = color
        self.md: list[str] = []

    def markdown(self) -> str:
        """The collected report, with runs of blank lines folded into one (a line ending in two spaces is a line break)."""
        out: list[str] = []
        for line in "\n".join(self.md).splitlines():
            if line.strip():
                out.append(line)
            elif out and out[-1]:
                out.append("")
        return "\n".join(out).strip() + "\n"

    def _c(self, text: str, style: str | None) -> str:
        return f"\033[{STYLES[style]}m{text}\033[0m" if (self.color and style) else text

    def title(self, text: str, sub: str = "") -> None:
        print()
        print(self._c(text, "title") + (f"  {self._c(sub, 'dim')}" if sub else ""))
        #* The first title is the report's own (h1); the sections below it are h2.
        self.md += ["", f"{'##' if self.md else '#'} {md_escape(text)}", ""] + ([f"*{md_escape(sub)}*", ""] if sub else [])

    def text(self, text: str, style: str | None = "dim") -> None:
        print(self._c(text, style))
        self.md.append(md_escape(ANSI.sub("", text)) + "  ")   # two trailing spaces: a line break

    def raw(self, terminal: str, markdown: str) -> None:
        print(terminal)
        self.md += ["", markdown, ""]

    def table(self, headers: list[str], rows: list[list[Any]], left: int = 1) -> None:
        """``left``: how many leading columns are left-aligned (the rest are right-aligned numbers)."""
        grid = [[cell(x) for x in row] for row in rows]
        widths = [max([len(h)] + [len(r[i].text) for r in grid]) for i, h in enumerate(headers)]
        fmt = lambda i, s: s.ljust(widths[i]) if i < left else s.rjust(widths[i])
        print("  ".join(self._c(fmt(i, h), "head") for i, h in enumerate(headers)))
        print(self._c("─" * (sum(widths) + 2 * (len(widths) - 1)), "dim"))
        for r in grid:
            print("  ".join(self._c(fmt(i, c.text), c.style) for i, c in enumerate(r)))
        esc = md_escape
        self.md += ["", "| " + " | ".join(map(esc, headers)) + " |"]
        self.md.append("|" + "|".join([":--"] * left + ["--:"] * (len(headers) - left)) + "|")
        for r in grid:
            self.md.append("| " + " | ".join(f"**{esc(c.text)}**" if c.style == "best" else esc(c.text) for c in r) + " |")
        self.md.append("")


def fmt_us(x: float) -> str:
    if x < 1:
        return f"{x:.3f}"
    if x < 10:
        return f"{x:.2f}"
    if x < 100:
        return f"{x:.1f}"
    return f"{x:,.0f}"


def timing_cell(res: Result | None, best: bool) -> Cell:
    if res is None:
        return Cell("")
    if res.status != "ok":
        return Cell(res.status, "bad" if res.status == "ERR" else "dim")
    text = fmt_us(res.median) + ("†" if res.dagger else "") + ("≠" if res.differs else "") + ("~" if res.spread > 0.15 else "")
    return Cell(text, "best" if best else ("dim" if res.dagger else None))


COVERAGE_CELLS = {
    ("reject", "reject"): ("✓ catches", "good"), ("reject", "accept"): ("✗ misses", "bad"),
    ("reject", "coerce"): ("~ coerces", "warn"), ("reject", "partial"): ("◐ sometimes", "warn"),
    ("accept", "accept"): ("✓ accepts", "good"), ("accept", "reject"): ("✗ rejects", "bad"),
    ("accept", "coerce"): ("~ converts", "warn"), ("accept", "partial"): ("◐ sometimes", "warn"),
    }


#* Timings this close to the fastest are a tie: run-to-run noise is larger than the gap.
TIE = 0.03


def fastest(res: dict[str, Result]) -> set[str]:
    """The checkers doing the full work (no †) whose median is the fastest, or within ``TIE`` of it."""
    fair = {k: r.median for k, r in res.items() if k != "plain" and r.status == "ok" and not r.dagger}
    if not fair:
        return set()
    limit = min(fair.values()) * (1 + TIE)
    return {k for k, v in fair.items() if v <= limit}


def linfit(xs: list[float], ys: list[float]) -> tuple[float, float]:
    mx, my = statistics.fmean(xs), statistics.fmean(ys)
    slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    return my - slope * mx, slope


def geomean(values: list[float]) -> float:
    return math.exp(statistics.fmean(math.log(v) for v in values))


