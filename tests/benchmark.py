def environment(libs: list[Lib]) -> dict[str, Any]:
    cpu = platform.processor() or platform.machine()
    try:
        with open("/proc/cpuinfo") as fh:
            cpu = next((l.split(":", 1)[1].strip() for l in fh if l.startswith("model name")), cpu)
    except OSError:
        if sys.platform == "darwin":
            try:
                cpu = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output = True, text = True).stdout.strip() or cpu
            except OSError:
                pass
    governor = None
    try:
        with open("/sys/devices/system/cpu/cpu0/cpufreq/scaling_governor") as fh:
            governor = fh.read().strip()
    except OSError:
        pass
    jit = getattr(sys, "_jit", None)
    return {
        "python": f"{platform.python_implementation()} {platform.python_version()}",
        "build": "free-threaded" if not getattr(sys, "_is_gil_enabled", lambda: True)() else "GIL",
        "jit": bool(jit and jit.is_enabled()) if jit else False,
        "platform": platform.platform(),
        "cpu": cpu, "cpus": os.cpu_count(), "governor": governor,
        "libs": {lib.key: lib.version() for lib in libs},
        }


