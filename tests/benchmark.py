def _drive(coro: Any) -> Any:
    """Run a coroutine that never actually suspends, without an event loop's overhead."""
    try:
        coro.send(None)
    except StopIteration as stop:
        return stop.value
    raise RuntimeError("coroutine suspended")


class Env:
    """Per-run state: the targets module and per-library class caches."""

    def __init__(self, T: Any) -> None:
        self.T = T
        self._classes: dict[str, dict[str, type] | Exception] = {}

    def classes(self, lib: Lib) -> dict[str, type]:
        if lib.key not in self._classes:
            try:
                built: dict[str, type] = {}
                for name, spec in CLASS_SPECS:
                    built[name] = lib.make_class(name, spec(built))
                self._classes[lib.key] = built
            except Exception as e:      # includes Unsupported
                self._classes[lib.key] = e
        result = self._classes[lib.key]
        if isinstance(result, Exception):
            raise result
        return result

    def target(self, name: str, lib: Lib) -> Callable[..., Any]:
        """A target function: from the targets module, or built for ``lib`` (validated values)."""
        build = VALIDATED_TARGETS.get(name)
        return getattr(self.T, name) if build is None else build(lib)

    def namespace(self, item: Case | Probe, lib: Lib, values: dict[str, Any] | None = None) -> dict[str, Any]:
        """Globals for running ``item.code`` against ``lib`` (raises Unsupported / setup errors)."""
        ns: dict[str, Any] = {"_drive": _drive, "_gc": gc}
        ns.update(item.values(self.T) if values is None else values)
        options = getattr(item, "pyvalidate_options", None)
        if options is not None:
            if not isinstance(lib, PyValidate):
                raise Unsupported
            ns["F"] = lib.function(self.target(item.target, lib), item.check_return, **options)
        elif item.kind in ("fn", "async"):
            ns["F"] = lib.function(self.target(item.target, lib), item.check_return)
        elif item.kind == "method":
            ns["obj"] = type("Service", (), {"m": lib.function(self.T.m_2, False)})()
        elif item.kind == "class":
            ns.update(self.classes(lib))
        return ns


def statement(case: Case) -> str:
    code = f"_drive({case.code})" if case.kind == "async" else case.code
    if case.expect_error:
        return f"try:\n    {code}\nexcept Exception:\n    pass"
    return code


@dataclasses.dataclass
class Result:
    status: str = "ok"            # "ok" | "n/a" | "ERR" | "no err"
    detail: str = ""
    samples: list[float] = dataclasses.field(default_factory = list)   # seconds per call
    dagger: bool = False
    differs: bool = False

    @property
    def median(self) -> float:
        return statistics.median(self.samples) * 1e6

    @property
    def best(self) -> float:
        return min(self.samples) * 1e6

    @property
    def spread(self) -> float:
        """Interquartile range relative to the median."""
        if len(self.samples) < 4:
            return 0.0
        q1, _, q3 = statistics.quantiles(self.samples, n = 4)
        return (q3 - q1) / statistics.median(self.samples)

    def as_json(self) -> dict[str, Any]:
        out: dict[str, Any] = {"status": self.status, "dagger": self.dagger}
        if self.detail:
            out["detail"] = self.detail
        if self.samples:
            out.update(median_us = self.median, best_us = self.best, rel_iqr = self.spread,
                       samples_us = [s * 1e6 for s in self.samples])
        return out


def _first_line(e: BaseException) -> str:
    text = re.sub(r"\x1b\[[0-9;]*m", "", str(e)).strip().splitlines()
    return f"{type(e).__name__}: {text[0][:90] if text else ''}"


def _calibrate(timer: timeit.Timer, min_time: float) -> int:
    """Smallest loop count whose run takes at least ``min_time`` (also warms caches)."""
    number = 1
    for _ in range(40):
        elapsed = timer.timeit(number)
        if elapsed >= min_time:
            return number
        number = number * 10 if elapsed <= 0 else max(number + 1, math.ceil(number * min_time / elapsed * 1.05))
    return number


def time_case(case: Case, libs: list[Lib], env: Env, coverage: dict[str, dict[str, str]], opts: argparse.Namespace,
              rng: random.Random) -> dict[str, Result]:
    results: dict[str, Result] = {}
    timers: dict[str, tuple[timeit.Timer, int]] = {}
    stmt = statement(case)
    setup = ("_gc.enable()\n" if opts.gc else "") + case.setup
    expected: Any = dataclasses.MISSING
    values = case.values(env.T)           # the very same inputs for every library

    for lib in libs:
        if lib.key == "plain" and case.expect_error:
            continue
        res = results[lib.key] = Result()
        try:
            ns = env.namespace(case, lib, values)
        except Unsupported:
            res.status = "n/a"
            continue
        except Exception as e:
            res.status, res.detail = "ERR", f"setup failed: {_first_line(e)}"
            continue

        #* Verify before timing: valid calls must pass, error cases must raise.
        check = dict(ns)
        try:
            exec(setup + "\n", check)
            if case.expect_error:
                try:
                    exec(f"_drive({case.code})" if case.kind == "async" else case.code, check)
                    res.status = "no err"
                    continue
                except Exception:
                    pass
            elif case.kind == "class":
                exec(case.code, check)
            else:
                exec(f"_r = {'_drive(' + case.code + ')' if case.kind == 'async' else case.code}", check)
                if expected is dataclasses.MISSING:
                    expected = check["_r"]
                elif check["_r"] != expected:
                    res.differs = True
        except Exception as e:
            res.status, res.detail = "ERR", f"rejected a valid call: {_first_line(e)}"
            continue

        res.dagger = any(
            PROBES_BY_KEY[p].expect == "reject" and coverage.get(p, {}).get(lib.key) in ("accept", "partial")
            for p in case.probes
            ) if lib.key != "plain" else False
        timer = timeit.Timer(stmt, setup or "pass", globals = ns)
        timers[lib.key] = (timer, _calibrate(timer, opts.min_time))

    #* Interleaved, shuffled rounds: slow drift (thermal, turbo, background load) hits every library alike.
    order = list(timers)
    for _ in range(opts.repeat):
        rng.shuffle(order)
        for key in order:
            timer, number = timers[key]
            results[key].samples.append(timer.timeit(number) / number)
    return results


def run_probes(libs: list[Lib], env: Env) -> tuple[dict[str, dict[str, str]], dict[str, str], dict[str, str]]:
    """Coverage matrix, plus 'all 3 wrong args reported' and a sample message per library."""
    coverage: dict[str, dict[str, str]] = {p.key: {} for p in PROBES}
    for probe in PROBES:
        for lib in libs:
            if lib.key == "plain":
                continue
            try:
                ns = env.namespace(probe, lib)
            except Unsupported:
                coverage[probe.key][lib.key] = "n/a"
                continue
            except Exception:
                coverage[probe.key][lib.key] = "ERR"
                continue
            outcomes = set()
            for _ in range(PROBE_TRIALS):
                trial = dict(ns)
                try:
                    exec(probe.setup + "\n", trial)
                except Exception:
                    outcomes.add("ERR")
                    break
                try:
                    exec(probe.code, trial)
                except Exception:
                    outcomes.add("reject")
                    continue
                coerced = probe.coerced(trial) if probe.coerced else _same(trial)
                outcomes.add("coerce" if coerced else "accept")
            coverage[probe.key][lib.key] = (outcomes.pop() if len(outcomes) == 1
                                            else "ERR" if "ERR" in outcomes
                                            else "partial" if "reject" in outcomes else "accept")

    reported: dict[str, str] = {}
    messages: dict[str, str] = {}
    for lib in libs:
        if lib.key == "plain":
            continue
        #* Functions where the library has them; class-only libraries (attrs, BaseModel) get the
        #* same inputs as a class built from the equivalent fields.
        probes = (
            (env.T.p_multi, "Multi", [("alpha", int, NO_DEFAULT), ("bravo", str, NO_DEFAULT), ("charlie", float, NO_DEFAULT)],
             {"alpha": "x", "bravo": 1, "charlie": "y"}, "multi"),
            (env.T.p_named, "Named", [("quantity", int, NO_DEFAULT)], {"quantity": "abc"}, "named"),
            )
        for target, class_name, fields, kwargs, sink in probes:
            try:
                try:
                    fn = lib.function(target, False)
                except Unsupported:
                    fn = lib.make_class(class_name, fields)
            except Unsupported:
                continue
            except Exception as e:
                (reported if sink == "multi" else messages)[lib.key] = f"setup failed: {_first_line(e)}"
                continue
            try:
                fn(**kwargs)
                text = None
            except Exception as e:
                text = f"{type(e).__name__}: {e}"
            if sink == "multi":
                plain = re.sub(r"\x1b\[[0-9;]*m", "", text or "")
                reported[lib.key] = f"{sum(n in plain for n in ('alpha', 'bravo', 'charlie'))}/3"
            else:
                messages[lib.key] = text or "(no error raised)"
    return coverage, reported, messages


# ═════════════════════════════════════════════════════════════════════════════
#  Cold start: one fresh interpreter per run, so nothing is cached or imported yet
# ═════════════════════════════════════════════════════════════════════════════

def cold_worker(lib_key: str, targets_dir: str) -> None:
    sys.path.insert(0, targets_dir)
    T = importlib.import_module(TARGETS_MODULE)
    lib = LIBS_BY_KEY[lib_key]
    ns = time.perf_counter_ns
    out: dict[str, Any] = {}

    #* Not timed here: this process has already imported much of the standard library (inspect,
    #* dataclasses, typing ...), which would hide part of every library's import cost. See bare_import_ms.
    lib.load()
    warnings.simplefilter("ignore")

    #* Warm the library's own internals on unrelated objects: we want *per-function* cold cost.
    try:
        lib.function(T.f_warm, False)(1)
        for name, args in (("f_2", (1, "x")), ("f_12", F12_ARGS)):
            fn = getattr(T, name)
            t = ns(); w = lib.function(fn, False); out[f"decorate_{name}"] = (ns() - t) / 1e3
            t = ns(); w(*args); out[f"first_{name}"] = (ns() - t) / 1e3
            t = ns(); w(*args); out[f"second_{name}"] = (ns() - t) / 1e3
    except Unsupported:
        pass

    try:
        lib.make_class("Warm", [("w", int, NO_DEFAULT)])(w = 1)
        fields = CLASS_SPECS[0][1]({})
        t = ns(); P = lib.make_class("Point", fields); out["define_class"] = (ns() - t) / 1e3
        t = ns(); P(x = 1, y = 2.0); out["first_construct"] = (ns() - t) / 1e3
    except Unsupported:
        pass

    try:
        lib.function(T.f_warm, False)
        gc.collect()
        tracemalloc.start()
        before = tracemalloc.get_traced_memory()[0]
        keep = []
        for name, args in T.MEM_CALLS:
            w = lib.function(getattr(T, name), False)
            w(*args)
            keep.append(w)
        gc.collect()
        out["mem_kb_per_fn"] = (tracemalloc.get_traced_memory()[0] - before) / len(keep) / 1024
        tracemalloc.stop()
    except Unsupported:
        pass

    print(json.dumps(out))


def _run_worker(command: list[str], env: dict[str, str], timeout: int) -> tuple[str | None, str | None]:
    """``(last line of stdout, None)``, or ``(None, why it failed)``."""
    try:
        proc = subprocess.run(command, capture_output = True, text = True, env = env, timeout = timeout)
    except subprocess.TimeoutExpired:
        return None, f"timed out after {timeout} s"
    lines = proc.stdout.strip().splitlines()
    if proc.returncode != 0 or not lines:
        return None, (proc.stderr.strip().splitlines() or ["worker failed"])[-1]
    return lines[-1], None


def bare_import_ms(lib: Lib, env: dict[str, str]) -> tuple[float | None, str | None]:
    """Time ``lib.import_code`` in an interpreter that has imported nothing else (what a user's program pays)."""
    if not lib.import_code:
        return 0.0, None
    code = f"import time; t = time.perf_counter_ns(); {lib.import_code}; print((time.perf_counter_ns() - t) / 1e6)"
    out, error = _run_worker([sys.executable, "-c", code], env, 120)
    return (float(out), None) if out is not None else (None, error)


def run_cold(libs: list[Lib], targets_dir: str, runs: int, progress: Callable[[str], None]) -> dict[str, dict[str, Any]]:
    env = _worker_env()
    results: dict[str, dict[str, Any]] = {}
    for lib in libs:
        samples: dict[str, list[float]] = {}
        error = None
        for i in range(runs):
            progress(f"cold start · {lib.key} · run {i + 1}/{runs}")
            import_ms, error = bare_import_ms(lib, env)
            if error:
                break
            samples.setdefault("import_ms", []).append(import_ms)   # type: ignore[arg-type]
            out, error = _run_worker([sys.executable, os.path.abspath(__file__), "--_cold-worker", lib.key, targets_dir],
                                     env, 300)
            if error:
                break
            for k, v in json.loads(out).items():                     # type: ignore[arg-type]
                samples.setdefault(k, []).append(v)
        results[lib.key] = {"error": error} if error else {k: statistics.median(v) for k, v in samples.items()}
    return results


