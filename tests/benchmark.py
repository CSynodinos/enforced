def error_cases(pattern: str | None) -> list[Case]:
    """The error-path cases selected by ``--cases`` (all of them without a pattern)."""
    return [c for c in CASES if c.section == S_ERR and (not pattern or re.search(pattern, f"{c.section} {c.name}", re.I))]


def message_worker(lib_key: str, targets_dir: str, repeat: int, min_time: float, pattern: str) -> None:
    sys.path.insert(0, targets_dir)
    T = importlib.import_module(TARGETS_MODULE)
    lib = LIBS_BY_KEY[lib_key]
    lib.load()
    warnings.simplefilter("ignore")
    env = Env(T)
    out: dict[str, Any] = {}
    for case in error_cases(pattern):
        try:
            ns = env.namespace(case, lib, case.values(T))
        except Unsupported:
            continue
        except Exception:
            out[case.name] = "ERR"
            continue
        code = f"_drive({case.code})" if case.kind == "async" else case.code
        check = dict(ns)
        exec(case.setup + "\n", check)
        try:
            exec(code, check)
            out[case.name] = "no err"
            continue
        except Exception as e:
            out.setdefault("_ansi", "\x1b[" in str(e))
        timer = timeit.Timer(f"try:\n    {code}\nexcept Exception as _e:\n    _s = str(_e)", case.setup or "pass", globals = ns)
        number = _calibrate(timer, min_time)
        out[case.name] = statistics.median(timer.timeit(number) / number for _ in range(repeat)) * 1e6
    print(json.dumps(out))


def _worker_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = dict(os.environ)
    #* The project root, so workers import this checkout of pyvalidate wherever the benchmark is started from.
    env["PYTHONPATH"] = os.pathsep.join(filter(None, [PROJECT_ROOT, os.getcwd(), env.get("PYTHONPATH")]))
    env["PYTHONWARNINGS"] = "ignore"
    env.update(extra or {})
    return env


def run_messages(libs: list[Lib], targets_dir: str, opts: argparse.Namespace,
                 progress: Callable[[str], None]) -> dict[str, dict[str, Any]]:
    available = {lib.key for lib in libs}
    results: dict[str, dict[str, Any]] = {}
    for column, key, extra in MESSAGE_VARIANTS:
        if key not in available:
            continue
        progress(f"error messages · {column}")
        out, error = _run_worker(
            [sys.executable, os.path.abspath(__file__), "--_message-worker", key, targets_dir, str(opts.repeat),
             str(opts.min_time), opts.cases or ""],
            _worker_env({"FORCE_COLOR": "1", **extra}), 600,
            )
        results[column] = {"error": error} if out is None else json.loads(out)
    return results


