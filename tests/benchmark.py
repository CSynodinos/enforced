def targets_source() -> str:
    lines = [TARGETS_BASE]
    for n in SCALING_SIZES:
        lines.append(f"def f_s{n}({', '.join(f'p{i}: int' for i in range(n))}): return p0")
    #* Varied arity and types, so per-shape caches can't trivially share everything.
    kinds = [("int", "1"), ("str", "'x'"), ("float", "1.0"), ("bool", "True"), ("bytes", "b'x'")]
    calls = []
    for i in range(MEM_FUNCTIONS):
        chosen = [kinds[(i + j) % len(kinds)] for j in range(i % 5 + 1)]
        lines.append(f"def f_mem_{i}({', '.join(f'a{j}: {t}' for j, (t, _) in enumerate(chosen))}): return a0")
        calls.append(f"('f_mem_{i}', ({', '.join(v for _, v in chosen)},))")
    lines.append(f"MEM_CALLS = [{', '.join(calls)}]")
    return "\n".join(lines) + "\n"


