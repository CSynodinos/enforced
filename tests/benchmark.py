class Unsupported(Exception):
    """The library has no equivalent of this feature."""


class Lib:
    key = ""                    # column name
    package: str | None = None  # distribution name, for the version
    module = ""                 # what load() imports (for the "not installed" note)
    import_code = ""            # what a user's program runs to get the library (timed in a bare interpreter)
    note = ""

    def load(self) -> None: ...

    def version(self) -> str:
        if self.package is None:
            return "-"
        try:
            return importlib.metadata.version(self.package)
        except importlib.metadata.PackageNotFoundError:
            mod = sys.modules.get(self.module)
            return getattr(mod, "__version__", "local")

    def function(self, fn: Callable[..., Any], check_return: bool) -> Callable[..., Any]:
        raise Unsupported

    def make_class(self, name: str, fields: list[tuple[str, Any, Any]]) -> type:
        raise Unsupported

    #* Validated values, in the library's own spelling (Unsupported: it has no way to say it).
    def positive_int(self) -> Any:
        """An int that must be > 0."""
        raise Unsupported

    def email(self) -> Any:
        """A str that must be a valid email address (the rules of pyvalidate's Email)."""
        raise Unsupported


def _email_rules() -> Callable[[str], str]:
    """The email rules every library's validator runs: returns the normalised address or raises ValueError."""
    from pyvalidate.data_types import Email
    return Email.validate


class Plain(Lib):
    key, note = "plain", "no checks: undecorated function / stdlib dataclass"

    def function(self, fn, check_return):
        return fn

    def make_class(self, name, fields):
        return dataclasses.dataclass(raw_class(name, fields))

    def positive_int(self):
        return int

    def email(self):
        return str


class PyValidate(Lib):
    key, package, module = "pyvalidate", "pyvalidate", "pyvalidate"
    import_code = "import pyvalidate"
    note = "@typecheck / pyvalidate.dataclass, defaults (convert on, coerce off)"

    def load(self):
        self.m = importlib.import_module("pyvalidate")

    def function(self, fn, check_return, **options):
        return self.m.typecheck(check_return = check_return, **options)(fn)

    def make_class(self, name, fields):
        return self.m.dataclass(raw_class(name, fields))

    def positive_int(self):
        return Annotated[int, lambda x: x > 0]

    def email(self):
        from pyvalidate.data_types import Email      # a TypeModel: an Email is built from a raw str
        return Email


