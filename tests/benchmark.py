class Pydantic(Lib):
    package, module = "pydantic", "pydantic"
    #* pydantic imports lazily: touch what load() and the decorators below use.
    import_code = "import pydantic, pydantic.dataclasses; pydantic.validate_call; pydantic.ConfigDict"

    def __init__(self, strict: bool) -> None:
        self.strict = strict
        self.key = "pyd.strict" if strict else "pydantic"
        self.note = ("validate_call / pydantic dataclass, strict=True (no coercion)" if strict
                     else "validate_call / pydantic dataclass, default lax mode (coerces)")

    def load(self):
        import pydantic
        self.pd = pydantic
        self.cfg = pydantic.ConfigDict(arbitrary_types_allowed = True, strict = self.strict)
        #* validate_assignment matches pyvalidate's default assignment checks.
        self.class_cfg = pydantic.ConfigDict(arbitrary_types_allowed = True, strict = self.strict, validate_assignment = True)

    def function(self, fn, check_return):
        return self.pd.validate_call(config = self.cfg, validate_return = check_return)(fn)

    def make_class(self, name, fields):
        from pydantic.dataclasses import dataclass as pydantic_dataclass
        return pydantic_dataclass(raw_class(name, fields), config = self.class_cfg)

    def positive_int(self):
        import annotated_types
        return Annotated[int, annotated_types.Gt(0)]

    def email(self):
        return Annotated[str, self.pd.AfterValidator(_email_rules())]


class PydanticModel(Pydantic):
    def __init__(self) -> None:
        super().__init__(strict = False)
        self.key, self.note = "pyd.model", "pydantic BaseModel (validate_assignment=True), classes only"
        self.import_code = "import pydantic; pydantic.create_model; pydantic.ConfigDict"

    def function(self, fn, check_return):
        raise Unsupported

    def make_class(self, name, fields):
        spec = {f: (t, ... if d is NO_DEFAULT else d) for f, t, d in fields}
        return self.pd.create_model(name, __config__ = self.class_cfg, **spec)


class Beartype(Lib):
    key, package, module = "beartype", "beartype", "beartype"
    import_code = "from beartype import beartype"
    note = "@beartype (O(1): checks one random item per collection)"

    def load(self):
        from beartype import beartype
        self.bt = beartype

    def function(self, fn, check_return):
        return self.bt(fn)          # return checked whenever annotated

    def make_class(self, name, fields):
        return self.bt(dataclasses.dataclass(raw_class(name, fields)))

    def positive_int(self):
        from beartype.vale import Is
        return Annotated[int, Is[lambda x: x > 0]]

    def email(self):
        from beartype.vale import Is
        rules = _email_rules()

        def valid(s: str) -> bool:
            try:
                return rules(s) is not None
            except ValueError:
                return False
        return Annotated[str, Is[valid]]


class Typeguard(Lib):
    key, package, module = "typeguard", "typeguard", "typeguard"
    import_code = "from typeguard import typechecked"
    note = "@typechecked (default: checks the first item of collections)"

    def load(self):
        from typeguard import typechecked
        self.tc = typechecked

    def function(self, fn, check_return):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            return self.tc(fn)      # return checked whenever annotated

