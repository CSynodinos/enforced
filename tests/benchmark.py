def raw_class(name: str, fields: list[tuple[str, Any, Any]]) -> type:
    """A bare class with annotations and defaults, ready for any dataclass-style decorator."""
    namespace: dict[str, Any] = {"__annotations__": {f: t for f, t, _ in fields}, "__module__": TARGETS_MODULE}
    namespace.update({f: d for f, _, d in fields if d is not NO_DEFAULT})
    return type(name, (), namespace)


